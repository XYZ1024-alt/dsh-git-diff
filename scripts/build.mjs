/**
 * Build both halves into committed, ready-to-run JavaScript:
 * - lib/index.js: the Host plugin (ESM, Node).
 * - lib/client.js: the browser plugin wrapped in the DSH module-loader
 *   envelope, with its CSS injected as an owned <style> tag.
 */
import { readFile } from 'node:fs/promises'
import { build } from 'esbuild'

const { name } = JSON.parse(await readFile(new URL('../package.json', import.meta.url), 'utf8'))

/** Modules the Web shell provides to every client plugin (its frozen platform table). */
const PLATFORM_MODULES = new Set([
  'react',
  'react/jsx-runtime',
  'react-dom',
  'react-dom/client',
  'zod',
  '@deepseek-ai/cordis',
  '@deepseek-ai/dsh-client-store',
  '@deepseek-ai/dsh-client-ui-slots',
  '@deepseek-ai/dsh-client-ui-primitives',
  '@deepseek-ai/dsh-client-ui-dockkit',
])

/** DSH packages small and dependency-free enough to inline into the client bundle. */
const INLINED = new Set(['@deepseek-ai/dsh-util-workspace-path'])

/** @type {import('esbuild').Plugin} */
const platformModules = {
  name: 'platform-modules',
  setup(build) {
    build.onResolve({ filter: /^[^./]/ }, ({ path }) => {
      if (PLATFORM_MODULES.has(path)) return { path, external: true }
      if (path.startsWith('@deepseek-ai/') && !INLINED.has(path)) {
        return { errors: [{ text: `"${path}" is neither a platform module nor inlined; import it as a type or add it to dsh.client.external` }] }
      }
      return undefined
    })
  },
}

const common = { bundle: true, target: 'es2023', charset: 'utf8', legalComments: 'none', logLevel: 'warning' }

await build({
  ...common,
  entryPoints: ['src/host/index.ts'],
  outfile: 'lib/index.js',
  platform: 'node',
  format: 'esm',
  packages: 'external',
  banner: { js: '// Generated by scripts/build.mjs from src/host. Do not edit.' },
})

const client = await build({
  ...common,
  entryPoints: { client: 'src/client/index.ts' },
  outdir: 'lib',
  platform: 'browser',
  format: 'cjs',
  jsx: 'automatic',
  minifyWhitespace: true,
  minifySyntax: true,
  plugins: [platformModules],
  write: false,
})

const output = (ext) => client.outputFiles.find((file) => file.path.endsWith(ext))?.text ?? ''
const css = output('.css').trim()
const styleTag =
  css === ''
    ? ''
    : `if(typeof document<"u"&&document.querySelector(${JSON.stringify(`style[data-plugin-css="${name}"]`)})===null){const s=document.createElement("style");s.dataset.plugin=${JSON.stringify(name)};s.dataset.pluginCss=${JSON.stringify(name)};s.textContent=${JSON.stringify(css)};document.head.appendChild(s)}\n`

const { writeFile } = await import('node:fs/promises')
await writeFile(
  'lib/client.js',
  `// Generated by scripts/build.mjs from src/client. Do not edit.
window.__ModuleLoader__.load({
id: ${JSON.stringify(name)},
factory: (require) => {
var module = { exports: {} };
var exports = module.exports;
${styleTag}${output('.js').trim()}
return module.exports;
}
});
`,
)
